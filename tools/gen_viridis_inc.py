#!/usr/bin/env python3
"""Generate the canonical 256-entry viridis LUT as a C include file.

Writes src/viridis_lut.inc with one "R, G, B" line per entry.
Needs matplotlib; run once and commit the generated file.
"""
import os
import sys

os.environ.setdefault("MPLCONFIGDIR", "/tmp/mpl-te15")

import numpy as np
import matplotlib

matplotlib.use("Agg")
import matplotlib.cm as cm

lut = cm.get_cmap("viridis")(np.linspace(0.0, 1.0, 256))
rgb = np.rint(lut[:, :3] * 255.0).astype(np.uint8)

out_path = sys.argv[1] if len(sys.argv) > 1 else "src/viridis_lut.inc"
with open(out_path, "w") as f:
    f.write("/* Auto-generated by tools/gen_viridis_inc.py — canonical viridis LUT.\n")
    f.write(" * 256 entries, R G B per line, values 0..255. */\n")
    for r, g, b in rgb:
        f.write(f"{{{r}, {g}, {b}}},\n")
print(f"wrote {out_path} ({len(rgb)} entries)")

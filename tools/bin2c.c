/*
 * bin2c — convert a binary file into a C array (build-time helper).
 *
 * usage: bin2c <input> <symbol>
 *
 * Writes `const unsigned char <symbol>[]` and
 * `const size_t <symbol>_len` to stdout. Used by the Makefile to embed the
 * About artwork in the executable so it is never read from disk at run time.
 */
#include <stdio.h>
#include <stdlib.h>

int main(int argc, char **argv)
{
    FILE *f;
    unsigned char buf[4096];
    size_t n, total = 0;
    int col = 0;

    if (argc != 3) {
        fprintf(stderr, "usage: %s <input> <symbol>\n", argv[0]);
        return 2;
    }
    f = fopen(argv[1], "rb");
    if (f == NULL) {
        perror(argv[1]);
        return 1;
    }
    printf("/* generated by tools/bin2c from %s - do not edit */\n", argv[1]);
    printf("#include <stddef.h>\n\n");
    printf("const unsigned char %s[] = {\n", argv[2]);
    while ((n = fread(buf, 1, sizeof(buf), f)) > 0) {
        for (size_t i = 0; i < n; i++) {
            if (col == 0) printf("  ");
            printf("0x%02x,", buf[i]);
            total++;
            if (++col == 16) {
                printf("\n");
                col = 0;
            } else {
                printf(" ");
            }
        }
    }
    if (col != 0) printf("\n");
    printf("};\n\n");
    printf("const size_t %s_len = %zu;\n", argv[2], total);
    fclose(f);
    return 0;
}
